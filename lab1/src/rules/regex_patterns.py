"""
Регулярные выражения для распознавания структурированных атрибутов ПДн.

Каждый паттерн возвращает совпадение (match), из которого извлекаются
индексы начала и конца сущности в тексте.

Атрибуты чётного варианта:
  INN, PASSPORT, BANK_CARD, OGRNIP, IP_ADDRESS, EMAIL,
  BIRTH_CERTIFICATE, KLADR, JOURNAL_ODD, JOURNAL_EVEN, SNILS, URL,
  MARRIAGE_CERTIFICATE, CADASTRAL_NUMBER, PHONE_NUMBER
"""

import re

# ИНН физического лица (12 цифр) или юридического лица (10 цифр)
# Используем word boundary (\b) чтобы не захватывать части более длинных чисел
INN_PATTERN = re.compile(r'\b(\d{12}|\d{10})\b')

# Серия и номер паспорта РФ: XXXX XXXXXX, XX-XX XXXXXX, с возможными знаками №/N
# Серия: 2 цифры региона + 2 цифры года выдачи, номер: 6 цифр (LR-REL-3)
PASSPORT_PATTERN = re.compile(
    r'\b(\d{2}[\s-]?\d{2})[\s-]*(?:[№N]\s*)?(\d{6})\b'
)

# Номер банковской карты: 13–19 цифр (Visa, MasterCard, МИР, Maestro, American Express)
# с поддержкой сплошных номеров, блочного формата 4-4-4-4 (+хвост) и маски Amex 4-6-5 (LR-REL-3)
BANK_CARD_PATTERN = re.compile(
    r'\b(?:'
    r'[2-6]\d{3}[\s-]\d{6}[\s-]\d{5}'                  # 15 цифр: American Express (4-6-5)
    r'|'
    r'[2-6]\d{3}(?:[\s-]\d{4}){2,3}(?:[\s-]\d{1,4})?' # 13-19 цифр: блочный формат через пробел/дефис
    r'|'
    r'[2-6]\d{12,18}'                                  # 13-19 цифр: сплошной номер
    r')\b'
)

# ОГРНИП: ровно 15 цифр, начинается с 3 или 4
OGRNIP_PATTERN = re.compile(r'\b([34]\d{14})\b')

# IP-адрес: IPv4 формат X.X.X.X (каждый октет 0–255)
IP_ADDRESS_PATTERN = re.compile(
    r'\b((?:25[0-5]|2[0-4]\d|[01]?\d\d?)\.(?:25[0-5]|2[0-4]\d|[01]?\d\d?)\.'
    r'(?:25[0-5]|2[0-4]\d|[01]?\d\d?)\.(?:25[0-5]|2[0-4]\d|[01]?\d\d?))\b'
)

# E-mail: RFC 5322-совместимый паттерн с поддержкой Punycode и защитой от FP
EMAIL_PATTERN = re.compile(
    r'(?i)(?<![a-zа-яё0-9_./\\:?#@])'
    r'([a-zа-яё0-9](?:[a-zа-яё0-9_.+-]*[a-zа-яё0-9])?'
    r'@'
    r'(?:[a-zа-яё0-9](?:[a-zа-яё0-9-]*[a-zа-яё0-9])?\.)+'
    r'(?:[a-zа-яё]{2,}|xn--[a-z0-9]+))'
    r'(?![a-zа-яё0-9_-])'
)

# Свидетельство о рождении: римские цифры, дефис, две кириллические буквы,
# затем № или N, затем 6 цифр.
# Примеры: "II-АГ № 123456", "IV-МК №654321", "I-ЯБ N 987654"
BIRTH_CERTIFICATE_PATTERN = re.compile(
    r'((?:X{0,3}(?:IX|IV|V?I{0,3}))-[А-ЯЁ]{2}\s?[№N]\s?\d{6})'
)

# Код КЛАДР: 11, 13, 15 или 17 цифр
KLADR_PATTERN = re.compile(
    r'\b(\d{17}|\d{15}|\d{13}|\d{11})\b'
)

# Номер телефона (используется при расширении, формат РФ)
PHONE_PATTERN = re.compile(
    r'((?:\+?7|8)[\s\(\-]*?(?:\d[\s\(\)\-]*?){9}\d)'
)

# Дополнительные атрибуты КР. Журнальные номера распознаются только рядом
# с явной меткой, чтобы обычные числа не классифицировались ошибочно.
JOURNAL_ODD_PATTERN = re.compile(
    r'(?i)(?:JOURNAL[_ -]?ODD|ЖУРНАЛ[_ -]?НЕЧ[ЁЕ]Т(?:НЫЙ)?)[^\d]*(\d*[13579])'
)
JOURNAL_EVEN_PATTERN = re.compile(
    r'(?i)(?:JOURNAL[_ -]?EVEN|ЖУРНАЛ[_ -]?Ч[ЁЕ]ТНЫЙ)[^\d]*(\d*[02468])'
)
SNILS_PATTERN = re.compile(r'(?<!\d)(\d{3}[-\s]\d{3}[-\s]\d{3}\s?\d{2})(?!\d)')
URL_PATTERN = re.compile(
    r'(?i)\bhttps?://(?:[a-zа-яё0-9-]+\.)+[a-zа-яё]{2,}(?:/(?:[^\s<>]*[^\s<>.,;:!?)\]])?)?'
)
MARRIAGE_CERTIFICATE_PATTERN = re.compile(
    r'(?i)((?:[IVX]{1,4})-[А-ЯЁ]{2}\s?[№N]\s?\d{6})'
)
CADASTRAL_NUMBER_PATTERN = re.compile(
    r'(?<!\d)(\d{1,2}:\d{1,2}:\d{5,7}:\d{1,7})(?!\d)'
)

DATE_PATTERN = re.compile(
    r'\b(?:0[1-9]|[12]\d|3[01])[./-](?:0[1-9]|1[0-2])[./-](?:19|20)\d{2}\b'
)
